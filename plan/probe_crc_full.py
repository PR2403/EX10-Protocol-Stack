"""用'手册精确C代码语义'的CRC批量验证手册全部十六进制请求帧示例。"""

def crc_ex10(data: bytes, poly=0x1021, init=0xFFFF) -> int:
    reg = init
    for b in data:
        for m in (0x80,0x40,0x20,0x10,0x08,0x04,0x02,0x01):
            xor_flag = reg & 0x8000
            reg = (reg << 1) & 0xFFFF
            if b & m:
                reg |= 1
            if xor_flag:
                reg ^= poly
    return reg


def subcrc(data: bytes) -> int:
    return sum(data) & 0xFF


